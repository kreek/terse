#!/usr/bin/env python3
"""Validate each task's terse.json and vendor the shared verifier into the task.

Harbor uploads only a task's own tests/ directory into the sandbox, so shared
verifier code is copied into each task. This script is the single writer of
those copies. Run it after editing anything under eval/verifier/shared; CI runs
it with --check to fail on drift.

Per task it writes:
  environment/Dockerfile                  from verifier/shared/Dockerfile
  tests/test.sh                           from verifier/shared/test.sh
  tests/terse_lib.py                      from verifier/shared/terse_lib.py
  tests/reward.toml                       from verifier/shared/reward.toml (judge weight dropped when the task has no judge criteria)
  tests/graders/graders.py                from verifier/shared/graders/
  tests/skill_triggering/...              from verifier/shared/skill_triggering/
  tests/judge/prompt.md                   from verifier/shared/judge/prompt.md
  tests/judge/quality.toml                the shared header, the task's judge criteria, and
                                          verifier/shared/judge/flow.toml when terse.json sets judge_flow
  tests/judge/instruction.md              from the task's instruction.md

Per-task files it never touches: task.toml, instruction.md, environment/workspace/,
tests/terse.json.
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import sys
from pathlib import Path

EVAL_DIR = Path(__file__).resolve().parent.parent
TASKS_DIR = EVAL_DIR / "tasks"
SHARED_DIR = EVAL_DIR / "verifier" / "shared"
sys.path.insert(0, str(SHARED_DIR))
import terse_lib as tl  # noqa: E402

MATCHES = ("contains", "not_contains", "max_words")


def task_dirs() -> list[Path]:
    return sorted(p for p in TASKS_DIR.iterdir() if (p / "tests" / "terse.json").is_file())


def validate(task: Path, meta: dict) -> None:
    """A malformed terse.json would score 0 silently in every trial; fail the sync instead."""
    problems = []
    if meta.get("task") != task.name:
        problems.append(f"task is {meta.get('task')!r}, expected {task.name!r}")
    unknown = set(meta.get("intended_skills") or []) - tl.TERSE_SKILLS
    if not meta.get("intended_skills") or unknown:
        problems.append(f"intended_skills must name Terse skills; unknown: {sorted(unknown)}")
    deliverables = meta.get("deliverables") or []
    for grader in meta.get("graders") or []:
        if grader.get("match") not in MATCHES:
            problems.append(f"{grader.get('name')}: match must be one of {MATCHES}")
        if grader.get("path") not in deliverables:
            problems.append(f"{grader.get('name')}: path {grader.get('path')!r} is not a deliverable")
        if grader.get("match") == "max_words":
            if not str(grader.get("pattern", "")).isdigit():
                problems.append(f"{grader.get('name')}: a max_words pattern must be the word limit")
            continue
        try:
            re.compile(grader.get("pattern") or "")
        except re.error as exc:
            problems.append(f"{grader.get('name')}: pattern does not compile: {exc}")
    if not isinstance(meta.get("judge_flow", False), bool):
        problems.append("judge_flow must be true or false")
    if not meta.get("graders") and not has_judge(meta):
        problems.append("no graders and no judge criteria: the task would score nothing")
    if problems:
        raise SystemExit(f"{task.name}/tests/terse.json:\n  " + "\n  ".join(problems))


def has_judge(meta: dict) -> bool:
    return bool(meta.get("judge") or meta.get("judge_flow"))


def toml_string(text: str) -> str:
    return json.dumps(text, ensure_ascii=False)


def quality_toml(meta: dict) -> bytes:
    """The shared judge header, the task's own criteria, then the shared flow criterion when the task opts in."""
    tables = [f'\n[[criterion]]\nname = {toml_string(c["name"])}\ndescription = {toml_string(c["description"])}\n'
              'type = "binary"\n' for c in meta.get("judge") or []]
    flow = (SHARED_DIR / "judge" / "flow.toml").read_text() if meta.get("judge_flow") else ""
    return ((SHARED_DIR / "judge" / "quality.toml").read_text() + "".join(tables) + flow).encode()


def reward_toml(has_judge: bool) -> bytes:
    text = (SHARED_DIR / "reward.toml").read_text()
    return (text if has_judge else re.sub(r",\s*judge\s*=\s*[0-9.]+", "", text)).encode()


def planned_copies(task: Path) -> list[tuple[Path | bytes, Path]]:
    """(source file or generated bytes, destination) pairs for one task."""
    meta = tl.load_task_meta(task / "tests")
    validate(task, meta)
    tests = task / "tests"
    pairs: list[tuple[Path | bytes, Path]] = [
        (SHARED_DIR / "Dockerfile", task / "environment" / "Dockerfile"),
        (SHARED_DIR / "test.sh", tests / "test.sh"),
        (SHARED_DIR / "terse_lib.py", tests / "terse_lib.py"),
        (reward_toml(has_judge(meta)), tests / "reward.toml"),
        (SHARED_DIR / "skill_triggering" / "skill_triggering.py", tests / "skill_triggering" / "skill_triggering.py"),
    ]
    if meta.get("graders"):
        pairs.append((SHARED_DIR / "graders" / "graders.py", tests / "graders" / "graders.py"))
    if has_judge(meta):
        pairs += [
            (SHARED_DIR / "judge" / "prompt.md", tests / "judge" / "prompt.md"),
            (quality_toml(meta), tests / "judge" / "quality.toml"),
            (task / "instruction.md", tests / "judge" / "instruction.md"),
        ]
    return pairs


def source_bytes(source: Path | bytes) -> bytes:
    return source if isinstance(source, bytes) else source.read_bytes()


def write_copy(source: Path | bytes, dest: Path) -> None:
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_bytes(source_bytes(source))
    if isinstance(source, Path):
        shutil.copymode(source, dest)
    print(f"synced {dest.relative_to(EVAL_DIR)}")


def stale_files(task: Path, planned: set[Path]) -> list[Path]:
    """Files under tests/ that sync no longer writes, such as a judge dir left after its criteria went.

    RewardKit scores every directory it finds, so a stale one still counts.
    """
    tests = task / "tests"
    keep = planned | {tests / "terse.json"}
    return sorted(p for p in tests.rglob("*") if p.is_file() and p not in keep and "__pycache__" not in p.parts)


def sync(check: bool) -> int:
    drift: list[str] = []
    for task in task_dirs():
        if not (task / "environment" / "workspace").is_dir():
            raise SystemExit(f"{task.name}: missing environment/workspace/ (add a .gitkeep for an empty one)")
        pairs = planned_copies(task)
        for source, dest in pairs:
            if dest.is_file() and dest.read_bytes() == source_bytes(source):
                continue
            if check:
                drift.append(str(dest.relative_to(EVAL_DIR)))
                continue
            write_copy(source, dest)
        for stale in stale_files(task, {dest for _, dest in pairs}):
            if check:
                drift.append(f"{stale.relative_to(EVAL_DIR)} (stale)")
                continue
            stale.unlink()
            print(f"removed {stale.relative_to(EVAL_DIR)}")
    if drift:
        print("verifier files out of sync; run eval/scripts/sync_tests.py:", file=sys.stderr)
        for path in drift:
            print(f"  {path}", file=sys.stderr)
        return 1
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="report drift without writing")
    return sync(check=parser.parse_args().check)


if __name__ == "__main__":
    raise SystemExit(main())
